import assert from 'node:assert/strict';
import {summarizePhase as s} from './frame-phase-metrics.mjs';
const regular=s(Array.from({length:250},(_,i)=>(i+1)*40),0,10000);
assert.equal(regular.averageFps,25);assert.equal(regular.worstOneSecondFps,25);
assert.equal(regular.frameGapMs.p99,40);
const freeze=s([100,200,300,2300,2400],0,4000);
assert.equal(freeze.frameGapMs.max,2000);assert.equal(freeze.worstOneSecondFps,0);
assert.equal(freeze.longestNoNewFrameMs,2000);assert.equal(freeze.over1000ms,1);
assert.equal(s([100,200],0,5000).longestNoNewFrameMs,4800);
assert.equal(s([],0,3000).longestNoNewFrameMs,3000);
assert.equal(s([],0,3000).worstOneSecondFps,0);
assert.equal(s([100],0,500).worstOneSecondFps,null);
assert.equal(s([100,1100,1200,1300],1000,1400).frames,3);
assert.equal(s([100,1100,1200,1300],1000,1400).frameGapMs.max,100);
assert.throws(()=>s([2,1],0,3));assert.throws(()=>s([],1,1));
console.log('Frame phase metrics tests passed');
